import { NextRequest, NextResponse } from 'next/server';
import { getAllAgentProfiles, createAgentProfile } from '@/lib/db';
import type { AgentProfile } from '@/lib/orchestrator/agent-profile';

export async function GET() {
  try {
    const rows = getAllAgentProfiles();
    const profiles = rows.map((row) => ({
      ...JSON.parse(row.profile_json) as AgentProfile,
      source: row.source,
      created_at: row.created_at,
      updated_at: row.updated_at,
    }));
    return NextResponse.json({ profiles });
  } catch (error) {
    return NextResponse.json(
      { error: error instanceof Error ? error.message : 'Failed to get agent profiles' },
      { status: 500 },
    );
  }
}

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();

    if (!body.displayName) {
      return NextResponse.json(
        { error: 'Missing required field: displayName' },
        { status: 400 },
      );
    }

    if (!body.orchestrator) {
      return NextResponse.json(
        { error: 'Missing required field: orchestrator' },
        { status: 400 },
      );
    }

    // Build the full profile object
    const profile: AgentProfile = {
      id: body.id || undefined as never, // will be generated by DB if not provided
      displayName: body.displayName,
      description: body.description || '',
      version: body.version || '1.0.0',
      orchestrator: body.orchestrator,
      strategyId: body.strategyId || 'react-loop',
      strategyOptions: body.strategyOptions,
      toolProviderIds: body.toolProviderIds || [],
      inlineTools: body.inlineTools,
      systemPrompt: body.systemPrompt,
      promptTemplate: body.promptTemplate,
      permissionMode: body.permissionMode,
      permissionBrokerId: body.permissionBrokerId,
      contextPolicyId: body.contextPolicyId,
      multiRole: body.multiRole,
      workflow: body.workflow,
      delegate: body.delegate,
      model: body.model,
      providerId: body.providerId,
      maxSteps: body.maxSteps,
      timeoutSec: body.timeoutSec,
      source: 'user',
      icon: body.icon,
    };

    const row = createAgentProfile({
      id: body.id,
      display_name: profile.displayName,
      description: profile.description,
      version: profile.version,
      profile_json: JSON.stringify(profile),
      source: 'user',
    });

    return NextResponse.json(
      { profile: { ...JSON.parse(row.profile_json), source: row.source, created_at: row.created_at } },
      { status: 201 },
    );
  } catch (error) {
    return NextResponse.json(
      { error: error instanceof Error ? error.message : 'Failed to create agent profile' },
      { status: 500 },
    );
  }
}
